export const mdlMetadataBySourceKey = new Map(
  mdlIntermediateBooks.map((book) => [book.sourceKey, book])
);

export function sourceKeyFromName(fileName: string) {
  return fileName.match(/_(\d{10})(?:[^\d]*|\.pdf)$/i)?.[1] ?? null;
}

export function getMdlMetadataForFileName(fileName: string) {
  const key = sourceKeyFromName(fileName);
  return key ? mdlMetadataBySourceKey.get(key) ?? null : null;
}

export function getMdlTargetFileName(fileName: string, fallbackGrade: GradeId) {
  const sourceKey = sourceKeyFromName(fileName);
  const metadata = sourceKey ? mdlMetadataBySourceKey.get(sourceKey) : null;
  if (!sourceKey || !metadata) return null;

  return `${metadata.grade || fallbackGrade}_mdl_${metadata.subjectSlug}_${metadata.fileSlug}_${sourceKey}.pdf`;
}
